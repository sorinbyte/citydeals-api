/*
  The 30 placeholder venues, lifted from what the mobile app already ships in
  src/features/home/offers.ts + contact.ts. Same names, same coordinates — so once the clients
  switch to reading the API the screens look identical and any difference is a wiring bug rather
  than a data difference.

  Deals live in ./deals.ts and menus in ./menus.ts, both keyed by the slug below.

  All of it is invented Bucharest data. Real partners replace it wholesale at onboarding.

  Photo paths are relative on purpose. Clients prefix them with their own asset base URL; the
  domain isn't finalised and baking it into rows would mean a data migration to change it.
*/

